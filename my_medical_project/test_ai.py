import requests
import json

# 1. ฐานข้อมูลคู่มือแพทย์ (Knowledge Base) ที่คุณหามา
# (ใส่ไว้ตรงนี้ AI จะได้ดึงไปใช้แปลภาษาหมอเป็นภาษาคน)
MEDICAL_DICTIONARY = {
    "LDL": {"meaning": "ไขมันเลว (ตัวทำหลอดเลือดตีบ) ยิ่งน้อยยิ่งดี", "normal": "< 100 mg/dL"},
    "CHOLESTEROL": {"meaning": "คอเลสเตอรอลรวม (ไขมันในเลือดทั้งหมด) ยิ่งน้อยยิ่งดี", "normal": "< 200 mg/dL"},
    "TRIGLYCERIDE": {"meaning": "ไตรกลีเซอไรด์ (ไขมันจากแป้ง/น้ำตาล/แอลกอฮอล์)", "normal": "< 150 mg/dL"},
    "HDL-C": {"meaning": "ไขมันดี (ตัวเก็บกวาดขยะหลอดเลือด) ยิ่งสูงยิ่งดี", "normal": "> 40 (ชาย), > 50 (หญิง)"},
    "GLUCOSE": {"meaning": "ระดับน้ำตาลในเลือดตอนอดอาหาร (เช็คเบาหวาน)", "normal": "70 - 99 mg/dL"},
    "CREATININE": {"meaning": "ของเสียจากกล้ามเนื้อ (ถ้าไตพัง ค่านี้จะสูง)", "normal": "0.6 - 1.2 mg/dL"},
    "URIC ACID": {"meaning": "กรดยูริก (ถ้าสูงเกินไปจะตกตะกอนเป็นโรคเก๊าท์)", "normal": "3.5 - 7.2 mg/dL"},
    "AST": {"meaning": "เอนไซม์ตับ (ถ้าสูงแปลว่าเซลล์ตับกำลังอักเสบ/เสียหาย)", "normal": "10 - 40 U/L"}
    # (เดี๋ยวเราค่อยมาเติมให้ครบทุกตัวตอนทำเว็บจริง)
}

# 2. ข้อมูลจำลองที่สมมติว่ารับมาจากหน้าเว็บ
test_name = "LDL"
patient_value = 145

# ดึงข้อมูลจากฐานข้อมูลมาเตรียมไว้
blood_info = MEDICAL_DICTIONARY.get(test_name.upper(), {"meaning": "ไม่ทราบความหมายแน่ชัด", "normal": "ไม่ทราบเกณฑ์"})

# 3. เขียน Prompt สั่ง AI แบบ "มัดมือชก" ห้ามออกนอกลู่นอกทาง
prompt = f"""
คุณคือคุณหมอคนไทยที่ใจดีและอธิบายเก่ง จงอธิบายผลเลือดให้คนไข้ฟังตามข้อมูลด้านล่างนี้
ห้ามใช้ภาษาจีน ห้ามใช้ภาษาอื่นนอกจากภาษาไทยและศัพท์แพทย์ภาษาอังกฤษที่จำเป็น

ข้อมูลผลเลือด:
- ชื่อค่าเลือด: {test_name}
- ค่าที่ตรวจได้: {patient_value}
- เกณฑ์ปกติ: {blood_info['normal']}
- ความหมายของค่านี้: {blood_info['meaning']}

จงสรุปผลและให้คำแนะนำสั้นๆ ตามโครงสร้างนี้:
1. อธิบายสั้นๆ ว่าค่า {test_name} คืออะไร (อ้างอิงจากความหมายที่ให้ไป)
2. ผลการตรวจของคนไข้อยู่ในเกณฑ์ปกติหรือไม่
3. คำแนะนำในการดูแลตัวเอง 1-2 ข้อ
"""

print(f"🚀 กำลังส่งข้อมูลให้คุณหมอ AI วิเคราะห์ {test_name}...")

# 4. ส่งข้อมูลไปหา Ollama
url = "http://localhost:11434/api/generate"
data = {
    "model": "qwen2.5:3b",
    "prompt": prompt,
    "stream": False,
    "temperature": 0.3 # ปรับลดความครีเอทีฟลง เพื่อไม่ให้มันแต่งเรื่องหรือหลุดภาษาจีน
}

try:
    response = requests.post(url, json=data)
    result = response.json()['response']
    
    print("\n===============================")
    print("🎯 คำตอบจาก AI (ฉบับคุณหมอผู้เชี่ยวชาญ):")
    print(result.strip())
    print("===============================")
    
except Exception as e:
    print("⚠️ เชื่อมต่อ Ollama ไม่ได้! เช็กว่าเปิดโปรแกรมอยู่ไหม")